  async findAll<TFields extends string = '*'>(
    filter: { tagIds?: string[]; bookmarkIds?: string[] },
    options?: FindBookmarkTagOptions<TFields>,
  ) {
    let where = this.addTenantIdToQuery<BookmarkTagEntity>({
      deleteFlag: false,
    });

    if (filter.bookmarkIds && filter.bookmarkIds.length > 0) {
      where = this.setConditionFilter<BookmarkTagEntity>(where, {
        bookmark: { id: { $in: filter.bookmarkIds } },
      });
    }

    if (filter.tagIds && filter.tagIds.length > 0) {
      where = this.setConditionFilter<BookmarkTagEntity>(where, {
        tag: { id: { $in: filter.tagIds } },
      });
    }

    return this.em.find(BookmarkTagEntity, where, options);
  }

