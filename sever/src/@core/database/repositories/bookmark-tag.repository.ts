  /**
   * Bulk delete bookmark tags
   */
  async bulkDelete(filter: {
    bookmarkIds?: string[];
    tagIds?: string[];
  }): Promise<void> {
    if (!filter.bookmarkIds && !filter.tagIds) return;

    const bookmarkTags = await this.findAll({
      bookmarkIds: filter.bookmarkIds,
      tagIds: filter.tagIds,
    });

    const currentDate = new Date();
    for (const bookmarkTag of bookmarkTags) {
      bookmarkTag.deleteFlag = true;
      bookmarkTag.deletedAt = currentDate;
    }
  }

